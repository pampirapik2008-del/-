// вспомогательные генераторы: o2 — второй осциллятор с накоплением фазы в s[k], sq — меандр, lp — простой фильтр,
// ex — экспонента (огибающие), seq — нота из списка по времени
const sfxH = {
	o2: (s, k, f) => {
		s[k] = (s[k] || 0) + (6.2832 * f) / 22050;
		return Math.sin(s[k]);
	},
	sq: (v) => (v > 0 ? 1 : -1),
	lp: (s, k, v, a) => (s[k] = (s[k] || 0) + (v - (s[k] || 0)) * a),
	ex: Math.exp,
	seq: (t, notes, step) => notes[Math.min(notes.length - 1, (t / step) | 0)],
};
// звуки боя: крит, треск, рык, появление, старт, навык, ульта, стихии, враги, смерть босса
function sfxFight(B, mk, sw, rd) {
	const { o2, sq, lp, ex, seq } = sfxH;
	B.crit = mk(0.3, (t, s) => sw(s, 1760) * 0.28 * ex(-t * 26) + o2(s, "b", 70 + 160 * ex(-t * 22)) * 0.9 * ex(-t * 12) + rd() * 0.45 * ex(-t * 45));
	B.crack = mk(0.4, (t, s) => lp(s, "l", rd(), 0.5 * ex(-t * 9) + 0.04) * 1.4 * ex(-t * 9) * (0.6 + 0.4 * sq(Math.sin(t * 190))) + o2(s, "b", 90 * ex(-t * 6) + 40) * 0.5 * ex(-t * 10));
	B.roar = mk(1.1, (t, s) => {
		const f = 62 + 26 * Math.sin(t * 17) + 30 * ex(-t * 3),
			e = Math.min(1, t * 12) * ex(-t * 2.2);
		return (sq(sw(s, f)) * 0.22 + o2(s, "b", f * 1.5) * 0.3 + o2(s, "c", f * 0.5) * 0.5 + lp(s, "l", rd(), 0.12) * 0.9) * e;
	});
	B.spawn = mk(0.26, (t, s) => sw(s, 260 + 1100 * t * t * 9) * 0.3 * ex(-t * 9) + rd() * 0.08 * ex(-t * 30));
	B.start = mk(0.6, (t, s) => (sq(sw(s, seq(t, [330, 330, 440, 660], 0.11))) * 0.2 + o2(s, "b", seq(t, [165, 165, 220, 330], 0.11)) * 0.3) * ex(-(t % 0.11) * 4) * (1 - t / 0.6));
	B.abil = mk(0.28, (t, s) => lp(s, "l", rd(), 0.08 + t * 1.6) * 0.8 * Math.sin((t / 0.28) * Math.PI) + sw(s, 420 + 1500 * t) * 0.16 * ex(-t * 6));
	B.ult = mk(0.9, (t, s) => {
		const k = 1 + t * 0.9;
		return (sw(s, 220 * k) * 0.25 + o2(s, "b", 330 * k) * 0.2 + o2(s, "c", 440 * k) * 0.16 + sq(o2(s, "d", 110 * k)) * 0.08 + lp(s, "l", rd(), 0.3) * 0.25 * t) * Math.sin(Math.min(1, t / 0.9) * Math.PI) * 1.2;
	});
	B.holy = mk(0.7, (t, s) => (sw(s, 880) * 0.2 + o2(s, "b", 1320) * 0.16 + o2(s, "c", 1760) * 0.12 + o2(s, "d", 2640) * 0.06) * ex(-t * 5) + rd() * 0.05 * ex(-t * 30));
	B.ice = mk(0.34, (t, s) => sw(s, 2300 + 900 * Math.sin(t * 70)) * 0.2 * ex(-t * 11) + o2(s, "b", 3400) * 0.1 * ex(-t * 18) + lp(s, "l", rd(), 0.9) * 0.2 * ex(-t * 30));
	B.fire = mk(0.42, (t, s) => lp(s, "l", rd(), 0.16) * 1.5 * Math.min(1, t * 30) * ex(-t * 7) + o2(s, "b", 70 + 60 * ex(-t * 9)) * 0.4 * ex(-t * 8));
	B.poison = mk(0.34, (t, s) => sw(s, 190 + 320 * Math.abs(Math.sin(t * 38))) * 0.34 * ex(-t * 8) + lp(s, "l", rd(), 0.05) * 0.5 * ex(-t * 12));
	B.bolt = mk(0.34, (t, s) => rd() * 0.5 * ex(-t * 22) * (0.5 + 0.5 * sq(Math.sin(t * 310))) + sq(sw(s, 110)) * 0.22 * ex(-t * 9) + o2(s, "b", 2200 - 5200 * t) * 0.16 * ex(-t * 16));
	B.dark = mk(0.5, (t, s) => (sw(s, 84 + 18 * Math.sin(t * 31)) * 0.6 + o2(s, "b", 126 - 40 * t) * 0.3 + lp(s, "l", rd(), 0.03) * 0.6) * Math.sin((t / 0.5) * Math.PI) * 0.9);
	B.prism = mk(0.36, (t, s) => sw(s, seq(t, [1568, 2093, 2637, 3136], 0.06)) * 0.2 * ex(-(t % 0.06) * 22) * (1 - t / 0.36) + o2(s, "b", 5200) * 0.04 * ex(-t * 8));
	B.chaos = mk(0.34, (t, s) => sq(sw(s, 180 + 1700 * ((Math.sin(((t * 44) | 0) * 91.7) * 43758.5) % 1) ** 2)) * 0.16 * ex(-t * 6) + rd() * 0.1 * ex(-t * 20));
	B.slime = mk(0.2, (t, s) => sw(s, 150 * ex(-t * 13) + 80) * 0.7 * ex(-t * 13) + lp(s, "l", rd(), 0.06) * 0.8 * ex(-t * 18));
	B.spit = mk(0.2, (t, s) => sw(s, 1300 - 4200 * t) * 0.24 * ex(-t * 13) + lp(s, "l", rd(), 0.3) * 0.2 * ex(-t * 25));
	B.dash = mk(0.34, (t, s) => lp(s, "l", rd(), 0.04 + t * 1.2) * 1.1 * Math.sin((t / 0.34) * Math.PI) + sw(s, 140 + 260 * t) * 0.2);
	B.bossdie = mk(1.5, (t, s) => (sw(s, 36 + 150 * ex(-t * 5)) * 0.9 + lp(s, "l", rd(), 0.2 * ex(-t * 2.4) + 0.02) * 1.3 + sq(o2(s, "b", 52 * ex(-t * 1.2))) * 0.12) * ex(-t * 2.4));
}
// звуки интерфейса и карты: выбор, расстановка, уровень, сундук, шаги, фанфары, раскрытие карты по редкости
function sfxUi(B, mk, sw, rd) {
	const { o2, sq, lp, ex, seq } = sfxH;
	B.pick = mk(0.07, (t, s) => sw(s, 760 + 900 * t) * 0.3 * ex(-t * 40));
	B.place = mk(0.14, (t, s) => sw(s, 210 * ex(-t * 16) + 90) * 0.6 * ex(-t * 20) + rd() * 0.25 * ex(-t * 60));
	B.lvl = mk(0.5, (t, s) => (sq(sw(s, seq(t, [523, 659, 784, 1047], 0.09))) * 0.16 + o2(s, "b", seq(t, [523, 659, 784, 1047], 0.09) * 2) * 0.1) * ex(-(t % 0.09) * 6) * (1 - t / 0.5));
	B.chest = mk(0.42, (t, s) => (t < 0.22 ? lp(s, "l", rd(), 0.2) * 0.5 * Math.sin((t / 0.22) * Math.PI) * (0.6 + 0.4 * Math.sin(t * 260)) : (sw(s, 180 * ex(-(t - 0.22) * 20) + 70) * 0.9 + rd() * 0.3) * ex(-(t - 0.22) * 16)));
	B.step = mk(0.34, (t, s) => {
		const q = t % 0.11;
		return (lp(s, "l", rd(), 0.1) * 0.9 + sw(s, 120) * 0.3) * ex(-q * 40) * 0.6;
	});
	B.fanfare = mk(1.6, (t, s) => {
		const n = seq(t, [523, 523, 659, 784, 1047, 1047, 1319, 1568], 0.16);
		return (sq(sw(s, n)) * 0.16 + o2(s, "b", n / 2) * 0.22 + o2(s, "c", n * 1.5) * 0.08) * ex(-(t % 0.16) * 3) * (1 - t / 1.7);
	});
	// раскрытие карты: чем выше редкость, тем длиннее и ярче фраза
	const SC = [523, 659, 784, 1047, 1319, 1568, 2093, 2637];
	for (let r = 0; r < 6; r++) {
		const n = 1 + r,
			st = r >= 4 ? 0.075 : 0.085,
			dur = n * st + 0.25 + r * 0.12;
		B["rev" + r] = mk(dur, (t, s) => {
			const i = Math.min(n - 1, (t / st) | 0),
				f = SC[i + (r >= 3 ? 1 : 0)],
				e = t < n * st ? ex(-(t % st) * 9) : ex(-(t - n * st) * (7 - r));
			return (sw(s, f) * 0.22 + sq(o2(s, "b", f)) * (0.05 + r * 0.012) + o2(s, "c", f * 2) * (r >= 2 ? 0.1 : 0) + o2(s, "d", f * 1.5) * (r >= 4 ? 0.1 : 0) + (r >= 3 ? rd() * 0.05 * ex(-(t % st) * 30) : 0)) * e * (r >= 4 ? 1.15 : 1);
		});
	}
}
// Каждый звук — функция (t, s) -> отсчёт; sw — синус с накоплением фазы, rd — шум. Буферы строятся один раз при запуске
// (порядок построения: бой, затем интерфейс).
function sfxBank() {
	Music.ext((B, mk, sw, rd) => {
		sfxFight(B, mk, sw, rd);
		sfxUi(B, mk, sw, rd);
	});
}
// настроение музыки: у каждого мира свой строй (сдвиг в полутонах) и тембр; бой с боссом — выше и резче
const Tune = {
	k: "",
	T: [
		[0, 20000],
		[2, 20000],
		[5, 20000],
		[-3, 9000],
		[-5, 3400],
		[7, 20000],
		[-7, 2800],
		[3, 20000],
		[-1, 6000],
		[-4, 20000],
	],
	upd() {
		const inRun = G && !Machine.is("menu", "settings", "pick"),
			w = inRun ? G.w || 0 : -1,
			b = Machine.is("fight", "prep") && F && F.kind === "boss" ? 1 + ((F.en[0] && F.en[0].bph) || 0) : 0,
			key = w + "|" + b;
		if (key === this.k) return;
		this.k = key;
		const q = w < 0 ? [0, 20000] : this.T[w];
		Music.tune(Math.pow(2, (q[0] + b) / 12), q[1]);
	},
};

// ---------- звук по событиям боя ----------
// Подписки стоят после частиц (50_draw.js): порядок обращений к Rand тот же, что при прямых вызовах.
Events.on("unit:hit", (tg, e) => {
	if (e.dot) return;
	if (e.crit) sfx("crit");
	else if (!e.quiet) sfx(e.snd || (e.el === "phys" || e.el === "nature" ? "hit" : e.el), 0.8);
});
Events.on("unit:phoenix", () => sfx("holy"));
Events.on("coin:gain", () => sfx("coin"));
Events.on("unit:died", (u) => sfx(u.boss ? "bossdie" : "die"));

